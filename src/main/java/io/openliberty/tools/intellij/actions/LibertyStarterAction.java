package io.openliberty.tools.intellij.actions;

import com.intellij.openapi.actionSystem.AnAction;
import com.intellij.openapi.actionSystem.AnActionEvent;
import com.intellij.openapi.actionSystem.ActionUpdateThread;
import com.intellij.openapi.project.Project;
import io.openliberty.tools.intellij.starter.LibertyNewProjectWizard;
import org.jetbrains.annotations.NotNull;

/**
 * Opens IntelliJ's Project wizard with the Liberty generator pre-selected.
 */
public class LibertyStarterAction extends AnAction {

    @Override
    public @NotNull ActionUpdateThread getActionUpdateThread() {
        return ActionUpdateThread.EDT;
    }

    @Override
    public void actionPerformed(@NotNull AnActionEvent e) {
        Project project = e.getProject();
        LibertyNewProjectWizard.show(project);
    }
}
